"""Generate the blank extraction workbook that ships beside the manuscript.

    python -m scripts.reporting.build_workbook
    python -m scripts.reporting.build_workbook --outdir <path>   # generate to a clean path

Every sheet is written from a declared schema source, so each column in the workbook can be traced
to a line of configuration rather than to someone's memory:

    studies_template.csv       config/extraction.yaml  ->  studies      (34 fields)
    estimates_template.csv     config/extraction.yaml  ->  estimates    (47 fields)
    risk_of_bias_template.csv  config/extraction.yaml  ->  risk_of_bias (12 fields, PROVISIONAL)
    data_dictionary.csv        all three of the above

This is distinct from `scripts.extraction.template`, which creates the *live* extraction tables in
`data/extraction/` seeded from full-text includes and refuses to run before any study is included.
This script creates the blank, publishable workbook, which exists precisely because nothing has been
included yet.

Two rules the generator enforces rather than trusts:

- **Headers only.** Every template is written with its header row and nothing else. There is no code
  path here that can emit a data row, because no study has been included, no estimate extracted and
  no appraisal performed; a workbook that appeared to contain results would misrepresent the review.
- **No invented appraisal.** The risk-of-bias sheet is structural only. The instrument is undecided
  (P023), so its domain names and judgement categories are absent by design, and `load_rob_schema()`
  refuses any field that carries a values list.

Output is deterministic: the same configuration produces byte-identical files, so the workbook can
be regenerated and compared rather than taken on trust.
"""
from __future__ import annotations

import argparse
import csv
import sys
from pathlib import Path

from scripts.common.config import ROOT, PipelineError
from scripts.extraction.schema import ESTIMATES, STUDIES, load_rob_schema, load_schema

DEFAULT_OUTDIR = ROOT / "results" / "manuscript" / "extraction_workbook"
DICT_COLUMNS = ("table", "field", "type", "required", "status", "depends_on", "description")
TEMPLATE_FILE = {STUDIES: "studies_template.csv",
                 ESTIMATES: "estimates_template.csv",
                 "risk_of_bias": "risk_of_bias_template.csv"}


def _write_csv(path: Path, rows: list[list[str]]) -> None:
    """Write with LF endings so the output is identical on every platform."""
    with open(path, "w", encoding="utf-8", newline="") as fh:
        csv.writer(fh, lineterminator="\n").writerows(rows)


def tables() -> dict:
    """Every sheet's schema, each from its declared source."""
    sch = load_schema()
    return {STUDIES: sch.table(STUDIES),
            ESTIMATES: sch.table(ESTIMATES),
            "risk_of_bias": load_rob_schema()}


def dictionary_rows(tbls: dict) -> list[list[str]]:
    rows = [list(DICT_COLUMNS)]
    for name, tbl in tbls.items():
        required = set(tbl.required)
        for f in tbl.fields:
            rows.append([name, f.name, f.type, "yes" if f.name in required else "no",
                         f.status, f.depends_on, f.description])
    return rows


README = """# Extraction workbook — TEMPLATES ONLY

These files contain **headers and no data rows**. No study has been included, so there is nothing to
extract, and nothing here has been appraised.

## How to regenerate

```
python -m scripts.reporting.build_workbook
```

The output is deterministic: the same configuration produces byte-identical files, so this workbook
can be regenerated and compared rather than taken on trust.

## Files and their schema sources

| File | Rows | Schema source | Purpose |
|---|---|---|---|
| `studies_template.csv` | 0 | `config/extraction.yaml` -> `studies` | One row per included study (`study_id`), {n_studies} fields |
| `estimates_template.csv` | 0 | `config/extraction.yaml` -> `estimates` | One row per effect estimate (`estimate_id`), {n_estimates} fields |
| `risk_of_bias_template.csv` | 0 | `config/extraction.yaml` -> `risk_of_bias` | One row per study per domain, {n_rob} fields. **PROVISIONAL** |
| `data_dictionary.csv` | {n_fields} | all three of the above | Field definitions, types, required flags, unresolved status |

Generated by `scripts/reporting/build_workbook.py`. It is a separate script from
`scripts/extraction/template.py`, which creates the *live* extraction tables under
`data/extraction/` and refuses to run until a study has been included at full text.

## Risk of bias is provisional, pending P023

The appraisal instrument **has not been chosen**. The risk-of-bias sheet carries structural columns
only — who assessed what, when, and on what evidence. The instrument's **domain names and judgement
categories are deliberately absent**: they come from whichever instrument P023 settles on and are
never invented here. Nothing in this workbook implies that any instrument has been adopted.

## Unresolved fields

These fields depend on a protocol decision that has not been made and must not be treated as
protocol-conformant until it is:

{unresolved}

## Recording values

Validation is enforced by `scripts/extraction/validate_extraction.py`. Missing is a value — record
`NR`, `NA` or `UNCLEAR`, never blank and never zero.
"""


def build(outdir: Path) -> dict:
    outdir.mkdir(parents=True, exist_ok=True)
    tbls = tables()

    for name, tbl in tbls.items():
        _write_csv(outdir / TEMPLATE_FILE[name], [list(tbl.columns)])

    rows = dictionary_rows(tbls)
    _write_csv(outdir / "data_dictionary.csv", rows)

    bullets = "\n".join(
        f"- `{f.name}` ({name}) — pending **{f.depends_on}**"
        for name, tbl in tbls.items() for f in tbl.fields if f.is_unresolved
    ) or "- none"
    (outdir / "README.md").write_text(
        README.format(n_studies=len(tbls[STUDIES].fields),
                      n_estimates=len(tbls[ESTIMATES].fields),
                      n_rob=len(tbls["risk_of_bias"].fields),
                      n_fields=len(rows) - 1,
                      unresolved=bullets),
        encoding="utf-8", newline="\n")

    # The workbook must never ship a data row: assert it rather than assume it.
    for name in tbls:
        path = outdir / TEMPLATE_FILE[name]
        with open(path, encoding="utf-8", newline="") as fh:
            written = list(csv.reader(fh))
        if len(written) != 1:
            raise PipelineError(f"{path.name}: expected a header row and nothing else, "
                                f"found {len(written) - 1} data row(s)")
    return {"fields": len(rows) - 1, "sheets": len(tbls)}


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--outdir", default=str(DEFAULT_OUTDIR))
    args = ap.parse_args(argv)
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")

    outdir = Path(args.outdir)
    result = build(outdir)
    rel = outdir.relative_to(ROOT).as_posix() if outdir.is_relative_to(ROOT) else outdir
    print(f"  extraction workbook -> {rel}")
    print(f"  {result['sheets']} sheets, {result['fields']} documented fields, 0 data rows")
    return 0


if __name__ == "__main__":
    sys.exit(main())
