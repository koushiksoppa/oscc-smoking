"""Backfill the `suggestion` and `decision_basis` columns of the title/abstract worksheet.

    python -m scripts.screening.backfill_provenance --suggestions <file>           # dry run
    python -m scripts.screening.backfill_provenance --suggestions <file> --apply   # write

The 194 title/abstract decisions were recorded by adopting a suggestion set generated by tooling.
The worksheet had no column able to say so, so the provenance lived only in a commit message and
a reader of the file alone would see 194 decisions indistinguishable from adjudicated ones. This
restores the separation D010 requires, inside the data.

**No decision is changed.** The migration writes only the two new columns and asserts that
`decision`, `reason_code`, `reviewer`, `screened_date`, `notes` and every derived column are
byte-identical before and after. The basis is derived from the evidence, not assumed:

* decision equals the suggestion      -> `adopted_from_suggestion`
* decision differs from the suggestion -> `independently_adjudicated`, because a value that
  differs from what was proposed cannot have been adopted from it
* no decision recorded                -> the suggestion is still filled in; the basis stays empty

It is a dry run unless `--apply` is given, and it is idempotent: a worksheet already carrying a
basis for every decided row is reported as migrated and left alone.
"""
from __future__ import annotations

import argparse
import csv
import sys

from scripts.common.config import PipelineError
from scripts.screening import worksheet
from scripts.screening.vocabulary import ADJUDICATED, ADOPTED, TA, load_vocabulary

PRESERVE = ["decision", "reason_code", "reviewer", "screened_date", "notes"]


def read_csv(path) -> list[dict[str, str]]:
    with open(path, encoding="utf-8", newline="") as fh:
        return list(csv.DictReader(fh))


def basis_for(decision: str, suggestion: str, reason: str = "",
              suggestion_reason: str = "") -> str:
    """Adoption requires that *both* the decision and its reason match what was proposed.

    Keeping the decision but changing the reason is a judgement about why the record fails, and
    recording it as an adoption would hide that judgement.
    """
    if not decision:
        return ""
    if suggestion and decision == suggestion and reason == suggestion_reason:
        return ADOPTED
    return ADJUDICATED


def plan(rows: list[dict[str, str]], suggestions: list[dict[str, str]]) -> dict:
    """Work out the new column values. Pure: reads nothing, writes nothing."""
    vocab = load_vocabulary()
    sug = {r["report_id"]: (r.get("suggestion") or "").strip() for r in suggestions}
    sug_reason = {r["report_id"]: (r.get("suggested_reason_code") or "").strip()
                  for r in suggestions}

    missing = sorted({r["report_id"] for r in rows} - set(sug))
    if missing:
        raise PipelineError(
            f"{len(missing)} worksheet report(s) have no entry in the suggestion file: "
            f"{', '.join(missing[:10])}{' …' if len(missing) > 10 else ''}\n"
            "  Every row must be accounted for, or the provenance would be guessed for some."
        )
    bad = sorted({v for v in sug.values() if v and v not in vocab.decisions})
    if bad:
        raise PipelineError(f"suggestion file contains values that are not decisions: {bad}")

    decided = sum(1 for r in rows if (r.get("decision") or "").strip())

    out, counts = [], {ADOPTED: 0, ADJUDICATED: 0, "": 0}
    for r in rows:
        new = dict(r)
        rid = r["report_id"]
        decision = (r.get("decision") or "").strip()
        reason = (r.get("reason_code") or "").strip()
        new["suggestion"] = sug[rid]
        new["suggestion_reason_code"] = sug_reason[rid]
        new["decision_basis"] = basis_for(decision, sug[rid], reason, sug_reason[rid])
        counts[new["decision_basis"]] += 1
        out.append(new)

    # Idempotent in the strict sense: nothing to do when the file already says exactly this.
    unchanged = all(
        (r.get(c) or "") == (n.get(c) or "")
        for r, n in zip(rows, out)
        for c in ("suggestion", "suggestion_reason_code", "decision_basis"))
    return {"rows": out, "counts": counts, "decided": decided, "migrated": unchanged}


def verify(before: list[dict[str, str]], after: list[dict[str, str]]) -> None:
    """Refuse to proceed unless everything except the two new columns is untouched."""
    if len(before) != len(after):
        raise PipelineError(f"row count changed: {len(before)} -> {len(after)}")
    for b, a in zip(before, after):
        if b["report_id"] != a["report_id"]:
            raise PipelineError(f"row order changed at {b['report_id']}")
        for col in b:
            if col in ("suggestion", "suggestion_reason_code", "decision_basis"):
                continue
            if (b.get(col) or "") != (a.get(col) or ""):
                raise PipelineError(
                    f"{b['report_id']}: column {col!r} changed from {b.get(col)!r} to "
                    f"{a.get(col)!r}; this migration must not alter any recorded value")


def write(path, rows: list[dict[str, str]]) -> None:
    with open(path, "w", encoding="utf-8", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=worksheet.FIELDS[TA])
        w.writeheader()
        w.writerows(rows)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--suggestions", required=True,
                    help="the audit file holding what the tooling proposed")
    ap.add_argument("--apply", action="store_true", help="write the change (default: dry run)")
    args = ap.parse_args(argv)

    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")

    try:
        path = worksheet.worksheet_path(TA)
        if not path.exists():
            raise PipelineError(f"{path.name} not found")
        before = read_csv(path)
        result = plan(before, read_csv(args.suggestions))
        verify(before, result["rows"])
    except PipelineError as exc:
        print(f"FAIL: {exc}", file=sys.stderr)
        return 1

    c = result["counts"]
    print(f"rows: {len(before)}  decisions recorded: {result['decided']}")
    print(f"  {ADOPTED:26s}: {c[ADOPTED]}")
    print(f"  {ADJUDICATED:26s}: {c[ADJUDICATED]}")
    print(f"  {'(no decision yet)':26s}: {c['']}")
    print("  suggestion_reason_code backfilled from the audit artefact")
    print("  every other column verified unchanged")

    if result["migrated"]:
        print("already migrated: every decided row has a basis; nothing to do")
        return 0
    if not args.apply:
        print("DRY RUN — nothing written. Re-run with --apply to write.")
        return 0

    write(path, result["rows"])
    print(f"-> {path.as_posix()}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
