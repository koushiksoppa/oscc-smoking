"""The extraction workbook must be reproducible and must never appear to hold results.

Regression for audit finding A-3: the shipped workbook claimed to be generated by
`build_manuscript.py`, which contains no reference to it, and no script in the repository actually
produced it. Its risk-of-bias sheet had no schema source at all.
"""
from __future__ import annotations

import csv

import pytest
import yaml

from scripts.common.config import PipelineError
from scripts.extraction import schema as schema_mod
from scripts.extraction.schema import ESTIMATES, STUDIES, load_rob_schema, load_schema
from scripts.reporting import build_workbook

SHEETS = ("studies_template.csv", "estimates_template.csv", "risk_of_bias_template.csv")


@pytest.fixture
def built(tmp_path):
    build_workbook.build(tmp_path)
    return tmp_path


def _rows(path):
    with open(path, encoding="utf-8", newline="") as fh:
        return list(csv.reader(fh))


def test_generates_every_file_from_a_clean_path(built):
    for name in SHEETS + ("data_dictionary.csv", "README.md"):
        assert (built / name).exists(), name


def test_templates_match_their_schema_source(built):
    sch = load_schema()
    expected = {"studies_template.csv": sch.table(STUDIES).columns,
                "estimates_template.csv": sch.table(ESTIMATES).columns,
                "risk_of_bias_template.csv": load_rob_schema().columns}
    for name, columns in expected.items():
        assert _rows(built / name)[0] == list(columns), name


def test_column_counts_are_preserved(built):
    assert len(_rows(built / "studies_template.csv")[0]) == 34
    assert len(_rows(built / "estimates_template.csv")[0]) == 47
    assert len(_rows(built / "risk_of_bias_template.csv")[0]) == 12


def test_no_sheet_carries_a_data_row(built):
    """A workbook that looked like it held results would misrepresent the review."""
    for name in SHEETS:
        assert len(_rows(built / name)) == 1, f"{name} has data rows"


def test_data_dictionary_documents_every_column_of_every_sheet(built):
    rows = list(csv.DictReader(open(built / "data_dictionary.csv", encoding="utf-8", newline="")))
    assert len(rows) == 34 + 47 + 12
    documented = {(r["table"], r["field"]) for r in rows}
    for table, name in (("studies", STUDIES), ("estimates", ESTIMATES)):
        for col in load_schema().table(name).columns:
            assert (table, col) in documented
    for col in load_rob_schema().columns:
        assert ("risk_of_bias", col) in documented


def test_generation_is_deterministic(tmp_path):
    a, b = tmp_path / "a", tmp_path / "b"
    build_workbook.build(a)
    build_workbook.build(b)
    for name in SHEETS + ("data_dictionary.csv", "README.md"):
        assert (a / name).read_bytes() == (b / name).read_bytes(), name


def test_readme_names_the_real_generator_and_command(built):
    readme = (built / "README.md").read_text(encoding="utf-8")
    assert "scripts/reporting/build_workbook.py" in readme
    assert "python -m scripts.reporting.build_workbook" in readme
    assert "TEMPLATES ONLY" in readme
    # the false claim this test exists to prevent
    assert "build_manuscript.py's companion step" not in readme


def test_risk_of_bias_is_marked_provisional_and_names_p023(built):
    readme = (built / "README.md").read_text(encoding="utf-8")
    assert "PROVISIONAL" in readme and "P023" in readme
    assert "has not been chosen" in readme
    rob = load_rob_schema()
    for name in ("tool", "domain", "judgement"):
        field = rob.field(name)
        assert field.is_unresolved and field.depends_on == "P023", name


def test_no_appraisal_instrument_is_named_or_implied(built):
    """Selecting an instrument is P023's to decide, not this script's."""
    blob = " ".join((built / n).read_text(encoding="utf-8") for n in SHEETS) + \
           (built / "data_dictionary.csv").read_text(encoding="utf-8")
    for instrument in ("Newcastle", "ROBINS", "ROB 2", "QUIPS", "GRADE", "Ottawa"):
        assert instrument.lower() not in blob.lower(), instrument


def test_rob_schema_may_not_assert_instrument_categories(tmp_path, monkeypatch):
    """A values list would assert the categories of an instrument nobody has chosen."""
    data = yaml.safe_load(open(schema_mod.EXTRACTION_CONFIG, encoding="utf-8"))
    data["risk_of_bias"]["fields"]["judgement"]["values"] = ["low", "high"]
    path = tmp_path / "extraction.yaml"
    path.write_text(yaml.safe_dump(data), encoding="utf-8")
    monkeypatch.setattr(schema_mod, "EXTRACTION_CONFIG", path)

    with pytest.raises(PipelineError, match="has not been chosen"):
        load_rob_schema()


def test_rob_schema_must_stay_marked_provisional(tmp_path, monkeypatch):
    data = yaml.safe_load(open(schema_mod.EXTRACTION_CONFIG, encoding="utf-8"))
    data["risk_of_bias"]["status"] = "adopted"
    path = tmp_path / "extraction.yaml"
    path.write_text(yaml.safe_dump(data), encoding="utf-8")
    monkeypatch.setattr(schema_mod, "EXTRACTION_CONFIG", path)

    with pytest.raises(PipelineError, match="provisional"):
        load_rob_schema()


def test_risk_of_bias_is_not_an_extraction_table():
    """It must not leak into the extraction data model while P023 is open."""
    assert set(load_schema().tables) == {STUDIES, ESTIMATES}
    assert schema_mod.RISK_OF_BIAS not in load_schema().tables


def test_build_refuses_to_emit_a_data_row(tmp_path, monkeypatch):
    """The headers-only guarantee is asserted by the generator, not assumed."""
    real = build_workbook._write_csv

    def sneak(path, rows):
        if path.name == "studies_template.csv":
            rows = rows + [["smuggled"] * len(rows[0])]
        real(path, rows)

    monkeypatch.setattr(build_workbook, "_write_csv", sneak)
    with pytest.raises(PipelineError, match="header row and nothing else"):
        build_workbook.build(tmp_path)
